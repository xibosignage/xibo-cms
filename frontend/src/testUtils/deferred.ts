/**
 * A promise you settle from the test, so a test can hold a request "in flight" and
 * check what the UI shows meanwhile (the controlled-promise pattern), then let it finish.
 *
 *   const upload = deferred<Response>();
 *   vi.mocked(api).mockReturnValue(upload.promise);
 *   // ...assert the pending state...
 *   upload.resolve(response);
 */
export const deferred = <T>() => {
  let resolve!: (value: T) => void;
  let reject!: (reason: unknown) => void;
  const promise = new Promise<T>((res, rej) => {
    resolve = res;
    reject = rej;
  });
  return { promise, resolve, reject };
};
